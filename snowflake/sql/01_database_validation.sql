USE DATABASE ATMOSYNC_DB;
USE SCHEMA RAW;

-- Check current database and schema
SELECT
    CURRENT_DATABASE() AS CURRENT_DATABASE,
    CURRENT_SCHEMA() AS CURRENT_SCHEMA;

-- Check SENSOR_EVENTS table
DESCRIBE TABLE SENSOR_EVENTS;

-- Check total records
SELECT COUNT(*) AS TOTAL_RECORDS
FROM SENSOR_EVENTS;

-- Check latest sensor events
SELECT
    EVENT_ID,
    EVENT_TS,
    CONTAINER_ID,
    COMMODITY,
    TEMPERATURE_C,
    HUMIDITY_PCT,
    VIBRATION_G,
    QUANTITY_KG
FROM SENSOR_EVENTS
ORDER BY EVENT_TS DESC
LIMIT 10;

-- Check duplicate event IDs
SELECT
    EVENT_ID,
    COUNT(*) AS EVENT_COUNT
FROM SENSOR_EVENTS
GROUP BY EVENT_ID
HAVING COUNT(*) > 1;