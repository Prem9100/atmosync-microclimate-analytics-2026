SELECT
    EVENT_ID,
    TEMPERATURE_C,
    HUMIDITY_PCT,
    VIBRATION_G,
    QUANTITY_KG
FROM {{ ref('sensor_events_analytics') }}
WHERE
    TEMPERATURE_C NOT BETWEEN 4 AND 16
    OR HUMIDITY_PCT NOT BETWEEN 75 AND 98
    OR VIBRATION_G NOT BETWEEN 0.1 AND 5.0
    OR QUANTITY_KG NOT BETWEEN 500 AND 2000
