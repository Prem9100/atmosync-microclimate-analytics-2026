-- Run in a Snowflake worksheet with a role allowed to create these objects.
CREATE WAREHOUSE IF NOT EXISTS ATMOSYNC_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ATMOSYNC_DB;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC_DB.RAW;

CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.SENSOR_EVENTS (
  EVENT_ID VARCHAR(36) NOT NULL,
  EVENT_TS TIMESTAMP_TZ NOT NULL,
  CONTAINER_ID VARCHAR(50) NOT NULL,
  COMMODITY VARCHAR(50) NOT NULL,
  TEMPERATURE_C FLOAT,
  HUMIDITY_PCT FLOAT,
  VIBRATION_G FLOAT,
  QUANTITY_KG NUMBER(10,2),
  INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE ROLE IF NOT EXISTS ATMOSYNC_ANALYST;
GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON DATABASE ATMOSYNC_DB TO ROLE ATMOSYNC_ANALYST;
GRANT USAGE ON SCHEMA ATMOSYNC_DB.RAW TO ROLE ATMOSYNC_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA ATMOSYNC_DB.RAW TO ROLE ATMOSYNC_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATMOSYNC_DB.RAW TO ROLE ATMOSYNC_ANALYST;
GRANT INSERT ON TABLE ATMOSYNC_DB.RAW.SENSOR_EVENTS TO ROLE ATMOSYNC_ANALYST;
